package com.example.pocketguard;


import static com.example.pocketguard.MainApplication.FCM_CHANNEL_ID;

import android.app.NotificationManager;
import android.app.PendingIntent;
import android.content.Context;
import android.content.Intent;
import android.content.SharedPreferences;
import android.graphics.Bitmap;
import android.graphics.BitmapFactory;
import android.graphics.Color;
import android.util.Log;
import android.widget.Toast;

import androidx.annotation.NonNull;
import androidx.core.app.NotificationCompat;

import com.google.firebase.messaging.FirebaseMessagingService;
import com.google.firebase.messaging.RemoteMessage;

import java.io.IOException;
import java.net.URL;
/**
 * This class extends FirebaseMessagingService to handle incoming FCM (Firebase Cloud Messaging) messages.
 * It is responsible for processing incoming messages, creating and displaying notifications accordingly.
 *
 * Design Patterns Used:
 * 1. Singleton Pattern: The FirebaseMessagingService class acts as a singleton instance for handling FCM messages within the application.
 * 2. Factory Method Pattern: Used in the creation of NotificationCompat.Builder. NotificationCompat.Builder serves as a factory method for building notifications.
 * 3. Observer Pattern: The onMessageReceived() method serves as an observer that listens for incoming FCM messages and triggers appropriate actions upon message reception.
 * 4. Adapter Pattern: RemoteMessage is adapted to NotificationCompat.Builder to create and display notifications based on the received FCM messages.
 *
 */
public class FCMMessageReceiverService extends FirebaseMessagingService {
    // Variables
    Bitmap bitmap;
    PendingIntent pendingIntent;
    // Constants
    public static final int NOTIFICATION_ID = 1002;
    /**
     * Called when a message is received from FCM.
     * Processes the incoming message and creates a notification to display.
     *
     * @param remoteMessage The received FCM message.
     */
    @Override
    public void onMessageReceived(@NonNull RemoteMessage remoteMessage) {
        // Implementation of message processing and notification creation
        super.onMessageReceived(remoteMessage);
        Log.d("Hello", "Checking when calling onMessageReceived: ");
        Log.d("Hello", "onMessageReceived: Msg Received From: " + remoteMessage.getFrom());

        if (remoteMessage.getNotification() != null) {
            String title = remoteMessage.getNotification().getTitle();
            String body = remoteMessage.getNotification().getBody();
            String image_url = String.valueOf(remoteMessage.getNotification().getImageUrl());

            try {
                URL uri = new URL(image_url);
                bitmap = BitmapFactory.decodeStream(uri.openConnection().getInputStream());
            } catch (IOException e) {
                System.out.println(e);
            }

            try {
                Intent intent = new Intent(this, HomeActivity.class);
                insert_message_data_inside_intent(remoteMessage,intent);   // Injecting Data
                pendingIntent = PendingIntent.getActivity(this, 100, intent, PendingIntent.FLAG_IMMUTABLE);
            } catch (IllegalArgumentException e) {
                e.printStackTrace();
                Log.d("Hello", "onMessageReceived: exception in Pending Intent" + e);
            }

            NotificationCompat.Builder notificationBuilder = new NotificationCompat.Builder(this, FCM_CHANNEL_ID);
            notificationBuilder.setAutoCancel(true)
                    .setSmallIcon(R.drawable.notification_feed)
                    .setContentTitle(title)
                    .setContentText(body)
                    .setContentIntent(pendingIntent)
                    .setLargeIcon(bitmap)
                    .setStyle(new NotificationCompat.BigPictureStyle()
                            .bigPicture(bitmap)
                            .bigLargeIcon(null))
                    .setColor(Color.GREEN);
            NotificationManager notificationManager = (NotificationManager) getSystemService(Context.NOTIFICATION_SERVICE);
            notificationManager.notify(NOTIFICATION_ID, notificationBuilder.build());
        }
        if (remoteMessage.getData().size() > 0) {
            Log.d("Hello", "Checking when calling onMessageReceived: Data: " + remoteMessage.getData().toString());
        }
    }
    /**
     * Called when messages are deleted from the FCM server.
     */
    @Override
    public void onDeletedMessages() {
        super.onDeletedMessages();
        Log.d("Hello", "Checking when calling onDeletedMessages: ");
    }
    /**
     * Called when a new token is generated by Firebase.
     * This typically happens when the app is installed or data is cleared.
     *
     * @param token The new FCM token generated by Firebase.
     */
    @Override
    public void onNewToken(@NonNull String token) { //Suppose App Uninstall or data clear:: tokon new token server a updaad korba ei function
        super.onNewToken(token);
        Log.d("Hello", "Checking when calling onNewToken: ");
    }
    /**
     * Inserts message data inside the intent for passing data to the activity.
     * This method is used to inject data into the intent for launching the appropriate activity when the notification is clicked.
     *
     * @param remoteMessage The received FCM message containing data.
     * @param intent        The intent to which the message data will be inserted.
     */
    private void insert_message_data_inside_intent(RemoteMessage remoteMessage, Intent intent) {
        for (String key : remoteMessage.getData().keySet()) {
            if (key.equals("key_link_fcm")) {

                SharedPreferences sp = getSharedPreferences(Key_SharedPreference.PREFS_KEY,MODE_PRIVATE);
                sp.edit().putString(Key_SharedPreference.FCM_NOTIFICATION_LINK,remoteMessage.getData().get(key)).apply();

            }
        }
    }
}
